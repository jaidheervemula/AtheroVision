"""
AtheroVision model service: a thin HTTP layer over the cad package.

    python -m uvicorn api.main:app --port 8000        (run from the project folder)

Endpoints
  GET  /health    models loaded, library versions, selected models
  GET  /metrics   cross-validated metrics per target + exact training ranges
  POST /predict   {"features": {...55 frontend fields...}, "explain": true}
  GET  /dataset/{row}  a real training patient (row 0-302): inputs, angiography outcome and
                   cross-validated prediction, for demonstrations (see api/dataset.py)
  GET  /docs      interactive API documentation (generated by FastAPI)

The models, preprocessing, validation and explanations are exactly those of
src/cad (inference.py, explain.py); this file adds no modelling logic.
Educational decision-support prototype; not a diagnostic tool.
"""

from __future__ import annotations

import json
import sys
from collections import OrderedDict
from pathlib import Path
from threading import Lock

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from cad.explain import CADExplainer  # noqa: E402
from cad.inference import CADPredictor, InputValidationError  # noqa: E402

from .adapter import AdapterError, build_metrics, build_response, to_model_input  # noqa: E402
from .dataset import DatasetPatients  # noqa: E402
from .operating_points import RULE, compute_operating_points  # noqa: E402
from .reality_check import RealityCheck  # noqa: E402
from .calibration import NOTE as CALIBRATION_NOTE, load_calibration  # noqa: E402

# Loaded once at start-up. CADPredictor checks every model file's SHA-256, classes and
# feature list against config/model_selection.json and refuses to start on a mismatch.
predictor = CADPredictor()
explainer = CADExplainer(predictor)
# Flagging cut-offs per target, from the saved cross-validation predictions (api/operating_points.py).
OPERATING_POINTS = compute_operating_points(PROJECT_ROOT)
METRICS = build_metrics(predictor.config, n_samples=len(explainer.background),
                        operating_points=OPERATING_POINTS, rule=RULE)
# Predicted vs observed, from the saved calibration reports (api/calibration.py).
METRICS["calibration"] = load_calibration(PROJECT_ROOT)
METRICS["calibration_note"] = CALIBRATION_NOTE
# Same file the explainer has just hash-checked against the config.
DATASET = DatasetPatients(PROJECT_ROOT / "data" / "raw" / predictor.config["data_file"], PROJECT_ROOT)
# Observed outcome rate among the patients with the closest cross-validated score (api/reality_check.py).
REALITY = RealityCheck(DATASET)

app = FastAPI(
    title="AtheroVision model service",
    description="Coronary artery disease and LAD/LCX/RCA stenosis model scores with explanations. "
                "Educational decision-support prototype; not a diagnostic tool.",
    version="1.0",
)
app.add_middleware(
    CORSMiddleware,
    allow_origin_regex=r"http://(localhost|127\.0\.0\.1)(:\d+)?",
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type"],
)


class PredictRequest(BaseModel):
    features: dict = Field(..., description="Patient fields as sent by the AtheroVision form.")
    explain: bool = Field(True, description="Include per-feature explanations (about 2 s; LAD is the slow one).")
    dataset_row: int | None = Field(None, description="Set when the features are an unedited dataset patient: "
                                                      "that patient is left out of their own reality check.")


# Small cache so toggling back to a recent input is instant (explanations take ~2 s).
_cache: "OrderedDict[str, dict]" = OrderedDict()
_cache_lock = Lock()
CACHE_SIZE = 64


def _cache_get(key):
    with _cache_lock:
        if key in _cache:
            _cache.move_to_end(key)
            return _cache[key]
    return None


def _cache_put(key, value):
    with _cache_lock:
        _cache[key] = value
        _cache.move_to_end(key)
        while len(_cache) > CACHE_SIZE:
            _cache.popitem(last=False)


@app.get("/health")
def health():
    cfg = predictor.config
    return {
        "status": "ok",
        "models": {t: cfg["tasks"][t]["model_name"] for t in cfg["tasks"]},
        "config_created": cfg.get("created_utc"),
        "training_versions": cfg.get("training_versions"),
    }


@app.get("/metrics")
def metrics():
    return METRICS


@app.post("/predict")
def predict(req: PredictRequest):
    try:
        patient, unused = to_model_input(req.features, predictor.schema)
    except AdapterError as e:
        raise HTTPException(status_code=422, detail={"message": "Invalid patient input", "errors": e.errors})

    key = json.dumps([patient, req.explain], sort_keys=True)
    cached = _cache_get(key)
    if cached is None:
        try:
            # Values outside the training range are accepted and reported as warnings, so the
            # interface can show the prediction together with a reliability notice.
            prediction = predictor.predict(patient, allow_out_of_range=True)
            explanation = explainer.explain(patient, allow_out_of_range=True) if req.explain else None
        except InputValidationError as e:
            raise HTTPException(status_code=422, detail={"message": "Invalid patient input", "errors": e.errors})
        cached = {"prediction": prediction, "explanation": explanation}
        _cache_put(key, cached)

    response = build_response(predictor.config, req.features, cached["prediction"], cached["explanation"], unused,
                              OPERATING_POINTS)
    return REALITY.add_to_response(response, req.dataset_row)


@app.get("/dataset/{row}")
def dataset_patient(row: int):
    """A real patient from the training data, with the outcome kept separate from the inputs."""
    try:
        return DATASET.get(row)
    except IndexError:
        raise HTTPException(status_code=404, detail={"message": f"Row must be 0-{len(DATASET) - 1}.", "errors": []})
